#!/usr/bin/env node
// Generates data.js from the YAML files in data/. The browser app opens via file:// and
// cannot fetch YAML, so the parsed figures are baked into data.js (committed).
// After editing any data file: node build.js && node test.js
'use strict';

const fs = require('fs');
const path = require('path');

// Minimal YAML reader for the constrained style used in data/*.yaml:
// nested maps by indentation, lists of maps or scalars, `key: value` scalars,
// full-line and trailing `#` comments. Values never contain `#`.
function parseYAML(text) {
  const lines = [];
  for (const rawLine of String(text).split(/\r?\n/)) {
    const withoutComment = rawLine.replace(/#.*$/, '');
    if (!withoutComment.trim()) continue;
    lines.push({ indent: withoutComment.match(/^ */)[0].length, text: withoutComment.trim() });
  }
  let cursor = 0;

  function parseScalar(rawValue) {
    const value = rawValue.trim();
    if (value === '' || value === 'null' || value === '~') return null;
    if (value === 'true') return true;
    if (value === 'false') return false;
    if (/^-?\d+$/.test(value)) return parseInt(value, 10);
    if (/^-?\d*\.\d+$/.test(value)) return parseFloat(value);
    if ((value.startsWith('"') && value.endsWith('"')) || (value.startsWith("'") && value.endsWith("'"))) {
      return value.slice(1, -1);
    }
    return value;
  }

  function parseEntry(line) {
    const match = line.match(/^([^:]+):(.*)$/);
    if (!match) throw new Error('Cannot parse YAML line: ' + line);
    return { key: match[1].trim(), value: parseScalar(match[2]) };
  }

  function parseBlock(indent) {
    if (cursor >= lines.length || lines[cursor].indent < indent) return null;
    return lines[cursor].text.startsWith('- ') ? parseList(indent) : parseMap(indent);
  }

  function parseMap(indent) {
    const result = {};
    while (cursor < lines.length && lines[cursor].indent === indent && !lines[cursor].text.startsWith('- ')) {
      const { key, value } = parseEntry(lines[cursor].text);
      cursor++;
      if (value !== null) {
        result[key] = value;
      } else if (cursor < lines.length && lines[cursor].indent > indent) {
        result[key] = parseBlock(lines[cursor].indent);
      } else {
        result[key] = null;
      }
    }
    return result;
  }

  function parseList(indent) {
    const result = [];
    while (cursor < lines.length && lines[cursor].indent === indent && lines[cursor].text.startsWith('- ')) {
      const itemText = lines[cursor].text.slice(2).trim();
      cursor++;
      if (itemText === '') {
        result.push(parseBlock(lines[cursor].indent));
        continue;
      }
      const looksLikeMap = /^([^:]+):.+$/.test(itemText);
      if (!looksLikeMap) {
        result.push(parseScalar(itemText));
        continue;
      }
      const item = {};
      const first = parseEntry(itemText);
      item[first.key] = first.value;
      while (cursor < lines.length && lines[cursor].indent > indent && !lines[cursor].text.startsWith('- ')) {
        const next = parseEntry(lines[cursor].text);
        item[next.key] = next.value;
        cursor++;
      }
      result.push(item);
    }
    return result;
  }

  return parseBlock(lines[0].indent);
}

// Flatten default.yaml into the flat id-keyed shape the form wiring reads and saves.
// "y" ids are me, "w" ids are the wife. Birth years are added at runtime from age_now.
function flattenDefaults(loaded) {
  const goal = loaded.goal, people = loaded.people, strategies = loaded.strategies, assumptions = loaded.assumptions;
  return {
    target: goal.monthly_income_today,
    retireAge: goal.retire_age,
    deathAge: goal.plan_until_age,
    inflation: goal.inflation_pct,
    rPost: goal.post_retirement_return_pct,
    'y-oa': people.me.ordinary_account,
    'y-sa': people.me.special_account,
    'y-ma': people.me.medisave_account,
    'w-oa': people.wife.ordinary_account,
    'w-sa': people.wife.special_account,
    'w-ma': people.wife.medisave_account,
    plan: strategies.cpf_life_plan,
    optOA: strategies.move_spare_oa_to_sa,
    ers: strategies.top_up_ra_to_ers,
    startAge: assumptions.life_payout_start_age,
    rsGrowth: assumptions.retirement_sum_growth_pct,
    countOA: assumptions.spend_leftover_oa,
  };
}

const dataDir = path.join(__dirname, 'data');
const readFile = (name) => fs.readFileSync(path.join(dataDir, name), 'utf8');

const defaultValues = parseYAML(readFile('default.yaml'));
const cpfLife = parseYAML(readFile('cpf_life_2026.yaml'));
const cpfRules = parseYAML(readFile('cpf_rules.yaml'));

const data = {
  defaults: flattenDefaults(defaultValues),
  defaultAgeNow: { me: defaultValues.people.me.age_now, wife: defaultValues.people.wife.age_now },
  cpfLife,
  cpfRules,
};

const output = `// Generated by build.js from data/*.yaml - do not edit by hand.
// Regenerate with: node build.js
(function (root) {
  const DATA = ${JSON.stringify(data, null, 2)};
  if (typeof module !== 'undefined') module.exports = DATA; else root.DATA = DATA;
})(this);
`;

fs.writeFileSync(path.join(__dirname, 'data.js'), output);
console.log('Wrote data.js from data/*.yaml');
